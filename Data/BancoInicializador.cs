CREATE INDEX IF NOT EXISTS ix_avaliacoes_barbeiro ON "Avaliacoes" (barbeiro_id);

CREATE TABLE IF NOT EXISTS "Favoritos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL REFERENCES "Usuarios"(id) ON DELETE CASCADE,
    barbeiro_id INTEGER NOT NULL REFERENCES "Barbeiros"(id) ON DELETE CASCADE,
    UNIQUE (cliente_id, barbeiro_id)
);

CREATE TABLE IF NOT EXISTS "ListaEspera" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL REFERENCES "Usuarios"(id) ON DELETE CASCADE,
    barbeiro_id INTEGER NOT NULL REFERENCES "Barbeiros"(id) ON DELETE CASCADE,
    data TIMESTAMP NOT NULL,
    servico_ids VARCHAR(100) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'Aguardando',
