using System.Data;
using Microsoft.EntityFrameworkCore;
using SalaoBeleza.Models;
using SalaoBeleza.Services;

namespace SalaoBeleza.Data;

// Cria/atualiza as tabelas sozinho ao iniciar a API (tudo "IF NOT EXISTS", pode rodar quantas vezes quiser)
// e cria o usuario administrador na primeira execucao.
public static class BancoInicializador
{
    public static async Task Inicializar(IServiceProvider servicos)
    {
        using var escopo = servicos.CreateScope();
        var db = escopo.ServiceProvider.GetRequiredService<AppDbContext>();
        var config = escopo.ServiceProvider.GetRequiredService<IConfiguration>();
        var log = escopo.ServiceProvider.GetRequiredService<ILoggerFactory>().CreateLogger("Banco");

        await AguardarBanco(db, log);
        await VerificarEsquemaAntigo(db);

        var conexao = db.Database.GetDbConnection();
        if (conexao.State != ConnectionState.Open)
            await conexao.OpenAsync();

        using (var cmd = conexao.CreateCommand())
        {
            cmd.CommandText = ScriptSql;
            await cmd.ExecuteNonQueryAsync();
        }

        await CriarAdministrador(db, config, log);
    }

    private static async Task AguardarBanco(AppDbContext db, ILogger log)
    {
        const int tentativas = 15;

        for (var i = 1; i <= tentativas; i++)
        {
            try
            {
                if (await db.Database.CanConnectAsync())
                    return;
            }
            catch
            {
                // tenta de novo
            }

            log.LogWarning("Aguardando o PostgreSQL ficar disponivel ({Tentativa}/{Total}). Se o erro persistir, rode: docker compose up -d", i, tentativas);
            await Task.Delay(TimeSpan.FromSeconds(3));
        }

        throw new InvalidOperationException(
            "Nao foi possivel conectar ao PostgreSQL. Confira se o container esta no ar (docker compose up -d) " +
            "e se a connection string do appsettings.json esta correta (porta 5433).");
    }

    private static async Task VerificarEsquemaAntigo(AppDbContext db)
    {
        var conexao = db.Database.GetDbConnection();
        if (conexao.State != ConnectionState.Open)
            await conexao.OpenAsync();

        using var cmd = conexao.CreateCommand();
        cmd.CommandText =
            "SELECT EXISTS (SELECT 1 FROM information_schema.columns " +
            "WHERE table_name = 'Servicos' AND column_name = 'Nome')";

        var resultado = await cmd.ExecuteScalarAsync();

        if (resultado is bool antigo && antigo)
        {
            throw new InvalidOperationException(
                "O banco tem tabelas de uma versao muito antiga do projeto (colunas como \"Nome\"). " +
                "Recrie o banco: docker compose down -v && docker compose up -d (os dados de teste serao apagados).");
        }
    }

    private static async Task CriarAdministrador(AppDbContext db, IConfiguration config, ILogger log)
    {
        var existe = await db.Usuarios.AnyAsync(u => u.Tipo == "Administrador");
        if (existe)
            return;

        var email = (config["Admin:Email"] ?? "admin@salao.com").Trim().ToLowerInvariant();
        var senha = config["Admin:Senha"] ?? "admin123";

        var jaExiste = await db.Usuarios.FirstOrDefaultAsync(u => u.Email.ToLower() == email);
        if (jaExiste != null)
        {
            log.LogWarning("Nenhum administrador encontrado, mas o e-mail {Email} ja existe como outro tipo de usuario.", email);
            return;
        }

        db.Usuarios.Add(new Usuario
        {
            Nome = "Administrador",
            Email = email,
            SenhaHash = SenhaHasher.Gerar(senha),
            Tipo = "Administrador"
        });

        await db.SaveChangesAsync();

        log.LogWarning("Administrador criado: {Email} / senha inicial definida em Admin:Senha. TROQUE A SENHA depois do primeiro acesso.", email);
    }

    private const string ScriptSql = """
CREATE TABLE IF NOT EXISTS "Usuarios" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL
);
ALTER TABLE "Usuarios" ADD COLUMN IF NOT EXISTS foto_url VARCHAR(300) NULL;

CREATE TABLE IF NOT EXISTS "Barbeiros" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE REFERENCES "Usuarios"(id) ON DELETE CASCADE,
    percentual_barbeiro NUMERIC(5,2) NOT NULL DEFAULT 70
);
ALTER TABLE "Barbeiros"
    ADD COLUMN IF NOT EXISTS ativo BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS especialidades VARCHAR(200) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS bio VARCHAR(1000) NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS "Servicos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    duracao_minutos INTEGER NOT NULL
);
ALTER TABLE "Servicos" ADD COLUMN IF NOT EXISTS ativo BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS "Agendamentos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL REFERENCES "Usuarios"(id) ON DELETE CASCADE,
    barbeiro_id INTEGER NOT NULL REFERENCES "Barbeiros"(id) ON DELETE CASCADE,
    servico_id INTEGER NOT NULL REFERENCES "Servicos"(id) ON DELETE CASCADE,
    data_hora TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Agendado',
    valor_servico NUMERIC(10,2) NOT NULL,
    percentual_barbeiro NUMERIC(5,2) NOT NULL,
    valor_barbeiro NUMERIC(10,2) NOT NULL,
    valor_administrador NUMERIC(10,2) NOT NULL
);
ALTER TABLE "Agendamentos"
    ADD COLUMN IF NOT EXISTS duracao_minutos INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS valor_desconto NUMERIC(10,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS valor_final NUMERIC(10,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS cupom_id INTEGER NULL,
    ADD COLUMN IF NOT EXISTS cupom_codigo VARCHAR(40) NULL,
    ADD COLUMN IF NOT EXISTS usou_fidelidade BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS criado_em TIMESTAMP NOT NULL DEFAULT now();

UPDATE "Agendamentos" a
   SET duracao_minutos = COALESCE((SELECT s.duracao_minutos FROM "Servicos" s WHERE s.id = a.servico_id), 30)
 WHERE a.duracao_minutos = 0;

UPDATE "Agendamentos"
   SET valor_final = valor_servico - valor_desconto
 WHERE valor_final = 0 AND valor_desconto = 0 AND valor_servico > 0;

UPDATE "Agendamentos" SET status = 'Agendado'
 WHERE status NOT IN ('Agendado', 'Concluido', 'Faltou', 'Cancelado');

ALTER TABLE "Agendamentos" DROP CONSTRAINT IF EXISTS chk_status_agendamento;
ALTER TABLE "Agendamentos" ADD CONSTRAINT chk_status_agendamento
    CHECK (status IN ('Agendado', 'Concluido', 'Faltou', 'Cancelado'));
ALTER TABLE "Agendamentos" DROP CONSTRAINT IF EXISTS chk_valor_administrador;

CREATE INDEX IF NOT EXISTS ix_agendamentos_barbeiro_data ON "Agendamentos" (barbeiro_id, data_hora);
CREATE INDEX IF NOT EXISTS ix_agendamentos_cliente ON "Agendamentos" (cliente_id);

DO $$
BEGIN
    CREATE UNIQUE INDEX IF NOT EXISTS ux_agendamento_barbeiro_hora
        ON "Agendamentos" (barbeiro_id, data_hora)
        WHERE status IN ('Agendado', 'Concluido');
EXCEPTION WHEN unique_violation THEN
    RAISE NOTICE 'Existem agendamentos duplicados; indice unico de horario nao criado.';
END $$;

CREATE TABLE IF NOT EXISTS "AgendamentoServicos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id INTEGER NOT NULL REFERENCES "Agendamentos"(id) ON DELETE CASCADE,
    servico_id INTEGER NOT NULL,
    nome VARCHAR(150) NOT NULL,
    preco NUMERIC(10,2) NOT NULL,
    duracao_minutos INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_agendamento_servicos_agendamento ON "AgendamentoServicos" (agendamento_id);

INSERT INTO "AgendamentoServicos" (agendamento_id, servico_id, nome, preco, duracao_minutos)
SELECT a.id, a.servico_id, s.nome, a.valor_servico, s.duracao_minutos
  FROM "Agendamentos" a
  JOIN "Servicos" s ON s.id = a.servico_id
 WHERE NOT EXISTS (SELECT 1 FROM "AgendamentoServicos" i WHERE i.agendamento_id = a.id);

CREATE TABLE IF NOT EXISTS "BarbeiroFotos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id INTEGER NOT NULL REFERENCES "Barbeiros"(id) ON DELETE CASCADE,
    url VARCHAR(300) NOT NULL,
    legenda VARCHAR(150) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS "HorariosTrabalho" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id INTEGER NOT NULL REFERENCES "Barbeiros"(id) ON DELETE CASCADE,
    dia_semana INTEGER NOT NULL,
    trabalha BOOLEAN NOT NULL,
    inicio TIME NOT NULL,
    fim TIME NOT NULL,
    almoco_inicio TIME NULL,
    almoco_fim TIME NULL
);
CREATE INDEX IF NOT EXISTS ix_horarios_barbeiro ON "HorariosTrabalho" (barbeiro_id);

CREATE TABLE IF NOT EXISTS "Folgas" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id INTEGER NOT NULL REFERENCES "Barbeiros"(id) ON DELETE CASCADE,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    motivo VARCHAR(150) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ix_folgas_barbeiro ON "Folgas" (barbeiro_id);

CREATE TABLE IF NOT EXISTS "Avaliacoes" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id INTEGER NOT NULL UNIQUE REFERENCES "Agendamentos"(id) ON DELETE CASCADE,
    cliente_id INTEGER NOT NULL REFERENCES "Usuarios"(id) ON DELETE CASCADE,
    barbeiro_id INTEGER NOT NULL REFERENCES "Barbeiros"(id) ON DELETE CASCADE,
